/* ------------------- LABs ejecutables en la VM real ------------------- */

function labVm(id: string, num: string, title: string, minutes: number, objetivo: string,
  pasos: string[][], esperado: string, comprobacion: string[], troubleshooting: string[][], aviso?: string) {
  const blocks = [
    p(`🎯 Objetivo: ${objetivo}`),
    h('Pasos (ejecútalos en tu terminal real)'),
    ...pasos.map((grupo): any =>
      grupo[0]?.startsWith('$')
        ? cmd({ caption: undefined }, ...grupo.map((l) => l.replace(/^\$\s?/, '')))
        : p(grupo.join(' ')),
    ),
    h('Resultado esperado'),
    p(esperado),
    h('Comprobación'),
    cmd({}, ...comprobacion),
    h('Troubleshooting'),
    tbl(['Síntoma', 'Causa probable', 'Arreglo'], troubleshooting),
    tip('Al terminar', 'Marca el módulo como completado y pulsa 🔄 Restablecer si quieres empezar el siguiente desde cero.'),
  ]
  if (aviso) blocks.push(danger('⚠️ Advertencia', aviso))
  return srvModule(id, num.replace('LAB ', ''), title, minutes, [objetivo], blocks, { level: num.includes('LAB 0') ? 'beginner' : 'intermediate' })
}

