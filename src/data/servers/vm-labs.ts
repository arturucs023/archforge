/* Curso «Linux en máquina virtual» — 12 laboratorios REALES (se ejecutan en la VM
   del usuario, no en la CLI de ArchForge) + proyecto final.
   Estructura por laboratorio: objetivo → prerrequisitos → pasos explicados →
   resultado esperado → comprobación → troubleshooting → volver atrás → avisos. */
import { cmd, danger, file, h, info, ol, out, p, tip, tbl, ul, warn } from '../helpers'
import { srvModule } from './types'
import type { Block } from '../../types'

function lab(
  id: string,
  num: string,
  title: string,
  minutes: number,
  objetivo: string,
  prereqs: string[],
  preparacion: string[],
  pasos: string[][],
  esperado: string,
  comprobacion: string[],
  troubleshooting: string[][],
  volverAtras: string,
  aviso?: string,
) {
  const blocks: Block[] = [
    p(`🎯 Objetivo: ${objetivo}`),
    h('Prerrequisitos'),
    ul(...prereqs),
    h('Preparación'),
    ol(...preparacion),
    h('Pasos (con el porqué de cada comando)'),
    ...pasos.map((grupo, gi): ReturnType<typeof cmd> | ReturnType<typeof p> =>
      grupo[0]?.startsWith('$')
        ? cmd({ caption: `bloque ${gi + 1}` }, ...grupo.map((l) => l.replace(/^\$\s?/, '')))
        : p(grupo.join(' ')),
    ),
    h('Resultado esperado'),
    p(esperado),
    h('Comprobación'),
    cmd({ caption: 'verificación' }, ...comprobacion),
    h('Troubleshooting'),
    tbl(['Síntoma', 'Causa probable', 'Arreglo'], troubleshooting),
    h('Cómo volver atrás'),
    p(volverAtras),
  ]
  if (aviso) blocks.push(danger('⚠️ Advertencia de seguridad', aviso))
  blocks.push(info('Recuerda', 'Estos comandos se ejecutan EN TU VM. ArchForge no los ejecuta ni los valida: tú verificas con tus propias comprobaciones. Snapshot antes de empezar si vas a tocar algo delicado.'))
  return srvModule(id, num, title, minutes, [objetivo], blocks, { level: 'intermediate' })
}

